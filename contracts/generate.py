"""Write contracts/generated/ from the Pydantic models (docs/proposal.md, section 4.8).

`python contracts/generate.py` writes oversight.schema.json, then contracts.ts through
json-schema-to-typescript, pinned in the frontend's lockfile. With `--check` it writes nothing and
fails if either file differs from what it would write, byte for byte.

Events and responses use the serialization schema, where every key is required; requests use the
validation schema, where optional keys may be left out.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any, cast

from pydantic import BaseModel, TypeAdapter
from pydantic.json_schema import GenerateJsonSchema, JsonSchemaMode
from pydantic_core import CoreSchema

from oversight_contracts import CONTRACT_VERSION, commands, events, plans, policy, queue, usage

HERE = Path(__file__).resolve().parent
GENERATED = HERE / "generated"
FRONTEND = HERE.parent / "frontend"

REQUESTS: list[type[BaseModel]] = [
    commands.DictateTask,
    commands.StartAgent,
    commands.ConfirmExamples,
    commands.EnqueueTask,
    commands.QueueRevision,
    commands.StartLead,
    commands.StopLead,
    commands.ReviewChange,
    commands.RevertChange,
    commands.AgentMessage,
    commands.ApproveChange,
    commands.RequestChanges,
    commands.RejectChange,
    commands.SaveFile,
    commands.SetMergeMode,
    commands.CreatePlan,
    commands.UpdatePlan,
    commands.PlanRevision,
    commands.RejectPlan,
]
RESPONSES: list[type[BaseModel]] = [
    commands.TaskDictated,
    commands.AgentCreated,
    commands.TreeResponse,
    commands.ChangeView,
    commands.HistoryPage,
    commands.LeadCreated,
    queue.QueueSnapshot,
    commands.GraphResponse,
    commands.FileContent,
    commands.FileSaved,
    commands.Health,
    commands.ErrorResponse,
    commands.PlanCreated,
    policy.MergeModeState,
    plans.Plan,
    usage.UsageView,
]

ROOT = "OversightContracts"
"""The schema's root: a title over the definitions, with no type of its own, so json2ts declares
every definition."""
NOTE = re.compile(r"^ \* (This interface was referenced by .*|via the `definition` .*)\n", re.M)

HEADER = """\
// Generated by contracts/generate.py from the Pydantic models in contracts/src. Do not edit:
// change the models through docs/proposal.md, section 4.9, and run `make contracts`.
"""


class Schema(GenerateJsonSchema):
    def field_title_should_be_set(self, schema: Any) -> bool:
        # json2ts would turn every titled field into a type of its own.
        return False


def without_ref_siblings(node: Any) -> Any:
    """Drop ref descriptions that duplicate named types; preserve ref defaults via allOf."""
    if isinstance(node, dict):
        mapping = cast(dict[str, Any], node)
        if "$ref" in mapping:
            others = set(mapping) - {"$ref", "description", "default"}
            if others:
                raise ValueError(f"keys beside {mapping['$ref']}: {sorted(others)}")
            if "default" in mapping:
                return {"allOf": [{"$ref": mapping["$ref"]}], "default": mapping["default"]}
            return {"$ref": mapping["$ref"]}
        return {key: without_ref_siblings(value) for key, value in mapping.items()}
    if isinstance(node, list):
        return [without_ref_siblings(value) for value in cast(list[Any], node)]
    return node


def build_schema() -> dict[str, Any]:
    inputs: list[tuple[str, JsonSchemaMode, CoreSchema]] = [
        ("ServerEvent", "serialization", TypeAdapter(events.ServerEvent).core_schema),
        *((m.__name__, "serialization", m.__pydantic_core_schema__) for m in RESPONSES),
        *((m.__name__, "validation", m.__pydantic_core_schema__) for m in REQUESTS),
    ]
    _, definitions = Schema(ref_template="#/$defs/{model}").generate_definitions(inputs)
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": f"Oversight contracts {CONTRACT_VERSION}, generated: run `make contracts`.",
        "title": ROOT,
        "$defs": without_ref_siblings(dict(sorted(definitions.items()))),
    }


def for_typescript(node: Any) -> Any:
    """Translate 2020-12 tuple syntax for the pinned json2ts converter, keeping the wire schema."""
    if isinstance(node, dict):
        mapping = cast(dict[str, Any], node)
        converted = {key: for_typescript(value) for key, value in mapping.items()}
        if "prefixItems" in converted:
            if "items" in converted:
                raise ValueError("json2ts conversion requires a fixed tuple without trailing items")
            converted["items"] = converted.pop("prefixItems")
        elif converted.get("type") == "array":
            # Bounded lists stay ordinary arrays for consumers; Pydantic and the unmodified
            # JSON Schema enforce their limits. Only explicit prefixItems become tuples.
            converted.pop("minItems", None)
            converted.pop("maxItems", None)
        return converted
    if isinstance(node, list):
        return [for_typescript(value) for value in cast(list[Any], node)]
    return node


def to_typescript(schema_text: str) -> str:
    pnpm = shutil.which("pnpm")
    if pnpm is None:
        sys.exit("pnpm is needed to generate the TypeScript types: run `make install`")
    done = subprocess.run(
        [
            *[
                pnpm,
                "--offline",
                "exec",
                "json2ts",
                "--unreachableDefinitions",
                "--no-additionalProperties",
            ],
            *["--bannerComment", ""],
        ],
        cwd=FRONTEND,
        input=json.dumps(for_typescript(json.loads(schema_text))),
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
    )
    if done.returncode != 0:
        sys.exit(f"json2ts failed (exit {done.returncode}):\n{done.stderr}")
    return f'{HEADER}\n{tidy(done.stdout)}\nexport const CONTRACT_VERSION = "{CONTRACT_VERSION}";\n'


def tidy(typescript: str) -> str:
    """Remove the schema's empty root type and the note json2ts adds above each definition."""
    root = f"export interface {ROOT} {{\n  [k: string]: unknown;\n}}\n"
    typescript = typescript.replace(root, "")
    typescript = NOTE.sub("", typescript)
    typescript = typescript.replace("\n *\n */\n", "\n */\n")  # a description's trailing blank line
    return typescript.replace("/**\n */\n", "")  # a comment that held only the note


def render() -> dict[str, str]:
    """Each generated file's name and its whole content."""
    schema_text = json.dumps(build_schema(), indent=2, ensure_ascii=False) + "\n"
    return {"oversight.schema.json": schema_text, "contracts.ts": to_typescript(schema_text)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="write nothing; fail on any drift")
    args = parser.parse_args()
    files = render()
    if args.check:
        stale = [
            name
            for name, text in files.items()
            if not (GENERATED / name).is_file() or (GENERATED / name).read_bytes() != text.encode()
        ]
        if stale:
            names = ", ".join(stale)
            sys.exit(f"contracts/generated is out of date ({names}): run `make contracts`")
        return
    GENERATED.mkdir(exist_ok=True)
    for name, text in files.items():
        (GENERATED / name).write_bytes(text.encode())


if __name__ == "__main__":
    main()
