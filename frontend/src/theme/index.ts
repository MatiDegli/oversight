// Read the root at call time, so consumers do not retain a stale theme selection.
// Adding another set to themes and CSS does not change this interface.
export function getActiveTheme(
  root = typeof document === "undefined" ? undefined : document.documentElement,
): (typeof themes)[keyof typeof themes] {
  const name = root?.dataset.theme ?? "dark";
  if (Object.hasOwn(themes, name)) return themes[name as keyof typeof themes];
  throw new Error(`Unsupported theme: ${name}`);
}
